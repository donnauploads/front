function slugify(s: string): string {
  return s
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
}

function initialsOf(name: string): string {
  // Pull the leading letter of each word, skipping noise tokens like
  // "the" / "&" / parens, so "Bath & Body Works" → "BBW", "AT&T" → "AT".
  const cleaned = name.replace(/[()'."]/g, "")
  const words = cleaned.split(/\s+|-|\//).filter(Boolean)
  const skip = new Set(["the", "of", "and", "&", "for"])
  const letters = words
    .filter((w) => !skip.has(w.toLowerCase()))
    .map((w) => w[0]!.toUpperCase())
    .join("")
  return (letters || cleaned.slice(0, 2)).slice(0, 3)
}

export const employers: Employer[] = RAW.map(([name, domain], i) => ({
  id: slugify(name),
  name,
  domain,
  short: initialsOf(name),
  logo: FALLBACK_COLORS[i % FALLBACK_COLORS.length]!,
}))
